import "server-only";
import { createHmac, scryptSync, timingSafeEqual } from "node:crypto";
import { cookies } from "next/headers";
import { redirect } from "next/navigation";
import { getCurrentUser } from "./user";

/**
 * Staff access to /admin, two ways in:
 *  1. Google sign-in for staff: the account's email must be listed in ADMIN_EMAILS or
 *     STAFF_EMAILS on the server. The role is read from the environment on every request,
 *     so removing an email revokes access at once; the client can never set a role.
 *  2. The owner's break-glass password (ADMIN_USERNAME + ADMIN_PASSWORD_HASH, scrypt,
 *     generated by `npm run admin:hash`): an HMAC-signed HttpOnly cookie for 8 hours, role admin.
 * staff — orders, inquiries, products (prices, stock, publishing, fitments), CSV export.
 * admin — everything, plus categories, brands, deleting products, CSV import and the audit log.
 */
import { ADMIN_COOKIE } from "./cookie-names";
export { ADMIN_COOKIE };
const SESSION_TTL_S = 8 * 60 * 60;

export type StaffRole = "admin" | "staff";
export type AdminSession = { sub: string; role: StaffRole; exp: number; via?: "password" | "google" };

const list = (v: string | undefined) =>
  (v ?? "")
    .split(/[,;\s]+/)
    .map((x) => x.trim().toLowerCase())
    .filter(Boolean);

/** Server-assigned staff role for an email, or null for customers. */
export function roleForEmail(email: string | null | undefined): StaffRole | null {
  const e = email?.trim().toLowerCase();
  if (!e) return null;
  if (list(process.env.ADMIN_EMAILS).includes(e)) return "admin";
  if (list(process.env.STAFF_EMAILS).includes(e)) return "staff";
  return null;
}

function secret(): string {
  const s = process.env.APP_SECRET?.trim();
  if (s) return s;
  if (process.env.NODE_ENV === "production") throw new Error("APP_SECRET must be set in production");
  return "gremu-dev-only-secret";
}

const sign = (payload: string) => createHmac("sha256", secret()).update(`admin:${payload}`).digest("base64url");

export function adminConfigured(): boolean {
  return Boolean(process.env.ADMIN_PASSWORD_HASH?.trim());
}

/**
 * scrypt cost per hash scheme:
 *  - "scrypt"   — legacy, Node defaults (N=2^14, r=8, p=1); still accepted.
 *  - "scrypt17" — OWASP-recommended N=2^17, r=8, p=1 (~8× costlier to brute-force). New hashes.
 */
const SCRYPT_PARAMS: Record<string, { N: number; r: number; p: number }> = {
  scrypt: { N: 2 ** 14, r: 8, p: 1 },
  scrypt17: { N: 2 ** 17, r: 8, p: 1 },
};

/** Verify "<scheme>.<salt>.<hash>" in constant time. */
export function verifyPassword(password: string, stored: string): boolean {
  const [scheme, salt, hash] = stored.split(/[.$]/);
  const params = SCRYPT_PARAMS[scheme];
  if (!params || !salt || !hash) return false;
  const expected = Buffer.from(hash, "base64url");
  const actual = scryptSync(password, Buffer.from(salt, "base64url"), expected.length, {
    ...params,
    maxmem: 256 * params.N * params.r, // 2× the 128·N·r working set
  });
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

/** True when the configured hash uses the weaker legacy cost (shown as a hint in the admin). */
export function adminHashIsLegacy(): boolean {
  return (process.env.ADMIN_PASSWORD_HASH ?? "").startsWith("scrypt.");
}

export function checkCredentials(username: string, password: string): boolean {
  const user = process.env.ADMIN_USERNAME?.trim() || "admin";
  const hash = process.env.ADMIN_PASSWORD_HASH?.trim();
  if (!hash) return false;
  const userOk = timingSafeEqual(Buffer.from(username.padEnd(64).slice(0, 64)), Buffer.from(user.padEnd(64).slice(0, 64)));
  const passOk = verifyPassword(password, hash); // always run, so timing does not reveal the username
  return userOk && passOk;
}

export async function startSession(username: string) {
  const session: AdminSession = { sub: username, role: "admin", exp: Math.floor(Date.now() / 1000) + SESSION_TTL_S };
  const payload = Buffer.from(JSON.stringify(session)).toString("base64url");
  (await cookies()).set(ADMIN_COOKIE, `${payload}.${sign(payload)}`, {
    httpOnly: true,
    secure: process.env.NODE_ENV === "production",
    sameSite: "lax",
    path: "/",
    maxAge: SESSION_TTL_S,
  });
}

export async function endSession() {
  (await cookies()).delete(ADMIN_COOKIE);
}

export async function getAdminSession(): Promise<AdminSession | null> {
  const viaPassword = await passwordSession();
  if (viaPassword) return viaPassword;
  // Google-signed-in staff (only real Google accounts; local dev test accounts never get staff rights).
  const user = await getCurrentUser().catch(() => null);
  if (!user || !user.authProviderId.startsWith("google:")) return null;
  const role = roleForEmail(user.email);
  return role ? { sub: user.email!, role, exp: 0, via: "google" } : null;
}

async function passwordSession(): Promise<AdminSession | null> {
  const raw = (await cookies()).get(ADMIN_COOKIE)?.value;
  if (!raw) return null;
  const [payload, sig] = raw.split(".");
  if (!payload || !sig) return null;
  const expected = Buffer.from(sign(payload));
  const given = Buffer.from(sig);
  if (expected.length !== given.length || !timingSafeEqual(expected, given)) return null;
  try {
    const s = JSON.parse(Buffer.from(payload, "base64url").toString()) as AdminSession;
    if (s.role !== "admin" || s.exp < Date.now() / 1000) return null;
    return { ...s, via: "password" };
  } catch {
    return null;
  }
}

/** Use at the top of every admin page. `need: "admin"` for owner-only sections. */
export async function requireAdmin(locale: string, need: StaffRole = "staff"): Promise<AdminSession> {
  const s = await getAdminSession();
  if (!s) redirect(`/${locale}/admin/login`);
  if (need === "admin" && s.role !== "admin") redirect(`/${locale}/admin?denied=1`);
  return s;
}

/** For server actions: the session if it has at least the given role, else null. */
export async function staffFor(need: StaffRole = "staff"): Promise<AdminSession | null> {
  const s = await getAdminSession();
  if (!s) return null;
  return need === "admin" && s.role !== "admin" ? null : s;
}
